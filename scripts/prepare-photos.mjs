// Prepares every photo in /public/photos for the site:
//  1. Converts color photos to black and white once (the design prints all
//     photos in B&W, so color data is wasted bytes). Already-B&W files are
//     left alone, so this is safe to re-run.
//  2. Writes a tiny blurred preview of each photo to src/lib/photo-blur.ts,
//     so a soft image shows instantly while the real one loads.
// Run after adding or replacing a photo:  node scripts/prepare-photos.mjs
import sharp from "sharp";
import { readdirSync, writeFileSync, renameSync } from "node:fs";

const dir = "public/photos";
const files = readdirSync(dir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
const blur = {};

for (const f of files) {
  const path = `${dir}/${f}`;
  const { channels } = await sharp(path).stats();
  const isGray =
    channels.length === 1 ||
    (Math.abs(channels[0].mean - channels[1].mean) < 0.5 && Math.abs(channels[1].mean - channels[2].mean) < 0.5);
  if (!isGray || channels.length > 1) {
    let img = sharp(path).grayscale();
    // Same look as the old CSS filter (contrast 1.08, brightness 1.02), applied only once, to color originals
    if (!isGray) img = img.linear(1.08, -(128 * 0.08) + 128 * 0.02);
    await img.toColourspace("b-w").jpeg({ quality: 82, mozjpeg: true, progressive: true }).toFile(path + ".tmp");
    renameSync(path + ".tmp", path);
    console.log(isGray ? "saved as single-channel B&W:" : "converted to B&W:", f);
  }
  const tiny = await sharp(path).resize(16).blur(1).jpeg({ quality: 50 }).toBuffer();
  blur[`/photos/${f}`] = `data:image/jpeg;base64,${tiny.toString("base64")}`;
}

writeFileSync(
  "src/lib/photo-blur.ts",
  `// Generated by scripts/prepare-photos.mjs. Do not edit by hand.\nexport const photoBlur: Record<string, string> = ${JSON.stringify(blur, null, 2)};\n`,
);
console.log(`${files.length} photos, previews written to src/lib/photo-blur.ts`);
